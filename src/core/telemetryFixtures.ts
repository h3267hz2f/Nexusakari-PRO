export function buildHydratedScoutProfiles(
  blacklistLedger: BlacklistEntry[] = INITIAL_BLACKLIST_LEDGER
): SummonerScoutProfile[] {
  const blacklistMap = new Map<string, BlacklistEntry>();
  blacklistLedger.forEach((b) => blacklistMap.set(b.puuid, b));

  // Initial pass to compute RPI
  const tempProfiles: SummonerScoutProfile[] = RAW_SCOUT_PROFILES.map((raw) => {
    const breakdowns = raw.recentMatches.map((m) => calculateContextAwareRpi(m));
    const avgRpi =
      Math.round(
        (breakdowns.reduce((s, b) => s + b.rpiScore, 0) / Math.max(1, breakdowns.length)) * 10
      ) / 10;
    return {
      ...raw,
      averageRpi: avgRpi,
      latestRpiBreakdown: breakdowns[0],
      tags: [],
    };
  });

  // Premade detection
  const { premadeGroups } = detectPremadeSquads(tempProfiles);
  const puuidToGroup = new Map<string, string>();
  for (const grp of premadeGroups) {
    for (const id of grp.memberPuuids) {
      puuidToGroup.set(id, grp.groupId);
    }
  }

  return tempProfiles.map((p) => {
    const premadeGroupId = puuidToGroup.get(p.puuid);
    const blacklistHit = blacklistMap.get(p.puuid);
    const tags = evaluateSummonerTags(p.recentMatches, premadeGroupId, blacklistHit);
    return {
      ...p,
      premadeGroupId,
      tags,
    };
  });
}

